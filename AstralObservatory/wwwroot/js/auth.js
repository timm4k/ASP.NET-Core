(() => {
    if (sessionStorage.getItem(AstralApi.accessKey)) location.href = "/observatory.html";
    let mode = "login";
    let method = "sms";
    const authForm = document.querySelector("#authForm");
    const message = document.querySelector("#authMessage");
    const nameInput = document.querySelector("#name");
    const emailInput = document.querySelector("#email");
    const phoneInput = document.querySelector("#phone");
    const passwordInput = document.querySelector("#password");
    const verificationCode = document.querySelector("#verificationCode");
    const verifyMessage = document.querySelector("#verifyMessage");
    const verifyInstructions = document.querySelector("#verifyInstructions");

    document.querySelectorAll(".auth-tab").forEach(tab => tab.addEventListener("click", () => {
        mode = tab.dataset.mode;
        document.querySelectorAll(".auth-tab").forEach(item => item.classList.toggle("active", item === tab));
        document.querySelectorAll(".register-only").forEach(item => item.classList.toggle("hidden", mode !== "register"));
        document.querySelector("#authTitle").textContent = mode === "login" ? "Return to your station" : "Create your observatory account";
        document.querySelector("#authSubtitle").textContent = mode === "login" ? "Your second factor will be requested next" : "Add an international phone number for SMS 2FA or use an authenticator app";
        document.querySelector("#authSubmit").textContent = mode === "login" ? "Continue" : "Create account";
        message.textContent = "";
    }));

    authForm.addEventListener("submit", async event => {
        event.preventDefault();
        message.textContent = "";
        try {
            if (mode === "register") {
                await AstralApi.request("/register", { method: "POST", body: JSON.stringify({ name: nameInput.value, email: emailInput.value, phoneNumber: phoneInput.value, password: passwordInput.value }) }, null);
                mode = "login";
            }
            const result = await AstralApi.request("/login", { method: "POST", body: JSON.stringify({ email: emailInput.value, password: passwordInput.value }) }, null);
            sessionStorage.setItem(AstralApi.pendingKey, result.challengeToken);
            show("methodStep");
        } catch (error) {
            message.textContent = error.message;
            message.className = "message error";
        }
    });

    document.querySelector("#smsMethod").addEventListener("click", async () => {
        method = "sms";
        try {
            const result = await AstralApi.request("/2fa/sms", { method: "POST" }, sessionStorage.getItem(AstralApi.pendingKey));
            document.querySelector("#verifyTitle").textContent = "Enter the SMS code";
            verifyInstructions.textContent = result.deliveryMode === "development"
                ? `SMS emulation is active, so no text message was sent Enter the code generated for ${result.maskedDestination} below`
                : `A real SMS was sent through Twilio to ${result.maskedDestination} Enter that six-digit code below`;
            document.querySelector("#totpSetup").classList.add("hidden");
            const hint = document.querySelector("#developmentCode");
            hint.textContent = result.developmentCode ? `Code to enter: ${result.developmentCode}` : "Check your phone for the SMS code";
            hint.classList.toggle("hidden", !result.developmentCode);
            show("verifyStep");
        } catch (error) { showError(error); }
    });

    document.querySelector("#totpMethod").addEventListener("click", async () => {
        method = "totp";
        try {
            const result = await AstralApi.request("/2fa/totp/setup", { method: "POST" }, sessionStorage.getItem(AstralApi.pendingKey));
            document.querySelector("#verifyTitle").textContent = "Connect your authenticator";
            verifyInstructions.textContent = "Scan the QR code in an authenticator app, then enter the six-digit code generated by that app";
            document.querySelector("#qrCode").src = result.qrCodeDataUrl;
            document.querySelector("#sharedKey").textContent = result.sharedKey;
            document.querySelector("#developmentCode").classList.add("hidden");
            document.querySelector("#totpSetup").classList.remove("hidden");
            show("verifyStep");
        } catch (error) { showError(error); }
    });

    document.querySelector("#verifyForm").addEventListener("submit", async event => {
        event.preventDefault();
        try {
            const result = await AstralApi.request(`/2fa/${method}/verify`, { method: "POST", body: JSON.stringify({ code: verificationCode.value }) }, sessionStorage.getItem(AstralApi.pendingKey));
            sessionStorage.setItem(AstralApi.accessKey, result.accessToken);
            sessionStorage.removeItem(AstralApi.pendingKey);
            location.href = "/observatory.html";
        } catch (error) {
            verifyMessage.textContent = error.message;
            verifyMessage.className = "message error";
        }
    });

    document.querySelector("#backToMethods").addEventListener("click", () => show("methodStep"));

    function show(id) {
        ["credentialsStep", "methodStep", "verifyStep"].forEach(value => document.querySelector(`#${value}`).classList.toggle("hidden", value !== id));
    }

    function showError(error) {
        verifyMessage.textContent = error.message;
        verifyMessage.className = "message error";
    }
})();
